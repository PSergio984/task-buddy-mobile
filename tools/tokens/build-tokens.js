export function runBuild() {
  const tokensPath = path.resolve(__dirname, 'tokens.json');
  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));
  const { cssOutput, tsMobileOutput } = compileTokens(tokens);

  const repoRoot = path.resolve(__dirname, '../..');
  const parentDir = path.resolve(repoRoot, '..');

  let localRepoName = '';
  try {
    const pkg = JSON.parse(fs.readFileSync(path.resolve(repoRoot, 'package.json'), 'utf8'));
    localRepoName = pkg.name || '';
  } catch {}

  const targets = [];

  // Local target based on current repository
  if (
    localRepoName === 'task-buddy-frontend' ||
    fs.existsSync(path.resolve(repoRoot, 'src/styles'))
  ) {
    targets.push({
      path: path.resolve(repoRoot, 'src/styles/tokens.css'),
      content: cssOutput,
      name: 'Web tokens (local)',
    });
  } else if (
    localRepoName === 'task-buddy-desktop' ||
    fs.existsSync(path.resolve(repoRoot, 'src-tauri'))
  ) {
    targets.push({
      path: path.resolve(repoRoot, 'src/tokens.css'),
      content: cssOutput,
      name: 'Desktop tokens (local)',
    });
  } else if (
    localRepoName === 'task-buddy-mobile' ||
    fs.existsSync(path.resolve(repoRoot, 'src/constants'))
  ) {
    targets.push({
      path: path.resolve(repoRoot, 'src/constants/colors.ts'),
      content: tsMobileOutput,
      name: 'Mobile tokens (local)',
    });
  }

  // Sibling project targets (when running in multi-repo checkout)
  const siblingFrontend = path.resolve(parentDir, 'task-buddy-frontend/src/styles/tokens.css');
  if (localRepoName !== 'task-buddy-frontend' && fs.existsSync(path.dirname(siblingFrontend))) {
    targets.push({
      path: siblingFrontend,
      content: cssOutput,
      name: 'Web tokens (sibling)',
    });
  }

  const siblingDesktop = path.resolve(parentDir, 'task-buddy-desktop/src/tokens.css');
  if (localRepoName !== 'task-buddy-desktop' && fs.existsSync(path.dirname(siblingDesktop))) {
    targets.push({
      path: siblingDesktop,
      content: cssOutput,
      name: 'Desktop tokens (sibling)',
    });
  }

  const siblingMobile = path.resolve(parentDir, 'task-buddy-mobile/src/constants/colors.ts');
  if (localRepoName !== 'task-buddy-mobile' && fs.existsSync(path.dirname(siblingMobile))) {
    targets.push({
      path: siblingMobile,
      content: tsMobileOutput,
      name: 'Mobile tokens (sibling)',
    });
  }

  const written = new Set();
  for (const target of targets) {
    const normalized = path.normalize(target.path);
    if (!written.has(normalized)) {
      fs.mkdirSync(path.dirname(target.path), { recursive: true });
      fs.writeFileSync(target.path, target.content, 'utf8');
      console.log(`✔ Generated ${target.name}: ${target.path}`);
      written.add(normalized);
    }
  }
}

const currentFile = path.resolve(fileURLToPath(import.meta.url));
const executedFile = process.argv[1] ? path.resolve(process.argv[1]) : '';

if (executedFile === currentFile) {
  runBuild();
}
